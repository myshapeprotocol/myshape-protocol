describe("CONFORMANCE-21: payload digest integrity (F7 fix, T1–T8)", () => {
  const a01 = clone(assertion01) as unknown as CPS0002Assertion;
  const receipt = clone(receipt01) as unknown as CPS0001Receipt;
  const NOW = Date.parse("2026-08-30T00:00:00.000Z");

  function resign(a: CPS0002Assertion): CPS0002Assertion {
    const payload = buildCanonicalAssertionPayload(a);
    const sig = ed25519.sign(
      new TextEncoder().encode(payload),
      hexToBytes(ATTESTER_SECRET),
    );
    a.signature.value = bytesToHex(sig);
    return a;
  }

  // T1 — valid payload + valid JCS digest → VALID
  it("T1: valid payload + valid JCS digest → VALID (both verifiers)", () => {
    const ref = verifyAssertion(clone(a01), clone(receipt), NOW);
    const sec = verifyWithSecond(clone(a01), clone(receipt), NOW);
    expect(ref.status).toBe("VALID");
    expect(sec.status).toBe("VALID");
  });

  // T2 — modify evidence.payload only → INVALID_PAYLOAD_DIGEST
  it("T2: modified payload + unchanged digest → INVALID_PAYLOAD_DIGEST (both)", () => {
    const a = clone(a01);
    (a.evidence.payload as Record<string, unknown>).note = "MUTATED-BY-F8-T2";
    const ref = verifyAssertion(clone(a), clone(receipt), NOW);
    const sec = verifyWithSecond(clone(a), clone(receipt), NOW);
    expect(ref.status).toBe("INVALID");
    expect(ref.reason).toBe("INVALID_PAYLOAD_DIGEST");
    expect(sec.status).toBe("INVALID");
    expect(sec.reason).toBe("INVALID_PAYLOAD_DIGEST");
    // Direct step-level check (V2.5 isolated):
    expect(verifyPayloadDigest(a)).toBe("INVALID_PAYLOAD_DIGEST");
    expect(secondVerifyPayloadDigest(a)).toBe("INVALID_PAYLOAD_DIGEST");
  });

  // T3 — modify payload + recompute digest + keep old signature → INVALID_SIGNATURE
  it("T3: modified payload + recomputed digest + old signature → INVALID_SIGNATURE (both)", () => {
    const a = clone(a01);
    (a.evidence.payload as Record<string, unknown>).note = "MUTATED-BY-F8-T3";
    a.evidence.payloadDigest = sha256Hex(canonicalSerialize(a.evidence.payload));
    // The digest now matches the mutated payload → V2.5 would pass;
    // the ordered pipeline must fail at V2 first (stale signature).
    expect(verifyPayloadDigest(a)).toBeNull();
    expect(secondVerifyPayloadDigest(a)).toBeNull();
    const ref = verifyAssertion(clone(a), clone(receipt), NOW);
    const sec = verifyWithSecond(clone(a), clone(receipt), NOW);
    expect(ref.status).toBe("INVALID");
    expect(ref.reason).toBe("INVALID_SIGNATURE");
    expect(sec.status).toBe("INVALID");
    expect(sec.reason).toBe("INVALID_SIGNATURE");
  });

  // T4 — modify payload + recompute digest + re-sign → VALID
  it("T4: modified payload + recomputed digest + re-signed → VALID (both)", () => {
    const a = clone(a01);
    (a.evidence.payload as Record<string, unknown>).note = "MUTATED-BY-F8-T4";
    a.evidence.payloadDigest = sha256Hex(canonicalSerialize(a.evidence.payload));
    resign(a);
    const ref = verifyAssertion(clone(a), clone(receipt), NOW);
    const sec = verifyWithSecond(clone(a), clone(receipt), NOW);
    expect(ref.status).toBe("VALID");
    expect(sec.status).toBe("VALID");
  });

  // T5 — malformed digest → INVALID_SCHEMA (V0), both verifiers
  it("T5: malformed digest ('zz') → INVALID_SCHEMA (both)", () => {
    const a = clone(a01);
    a.evidence.payloadDigest = "zz";
    expect(verifySchema(a)).toBe("INVALID_SCHEMA");
    const ref = verifyAssertion(clone(a), clone(receipt), NOW);
    const sec = verifyWithSecond(clone(a), clone(receipt), NOW);
    expect(ref.status).toBe("INVALID");
    expect(ref.reason).toBe("INVALID_SCHEMA");
    expect(sec.status).toBe("INVALID");
    expect(sec.reason).toBe("INVALID_SCHEMA");
  });

  it("T5b: prefixed digest ('sha256:<64hex>') → INVALID_SCHEMA (both)", () => {
    const a = clone(a01);
    a.evidence.payloadDigest = "sha256:" + a01.evidence.payloadDigest;
    expect(verifySchema(a)).toBe("INVALID_SCHEMA");
    const ref = verifyAssertion(clone(a), clone(receipt), NOW);
    const sec = verifyWithSecond(clone(a), clone(receipt), NOW);
    expect(ref.reason).toBe("INVALID_SCHEMA");
    expect(sec.reason).toBe("INVALID_SCHEMA");
  });

  // T6 — both verifiers identical status + reason across all digest cases
  it("T6: both verifiers agree on status+reason for every digest case", () => {
    const cases: CPS0002Assertion[] = [];
    const t2 = clone(a01);
    (t2.evidence.payload as Record<string, unknown>).note = "MUTATED-BY-F8-T6A";
    cases.push(t2);
    const t3 = clone(a01);
    (t3.evidence.payload as Record<string, unknown>).note = "MUTATED-BY-F8-T6B";
    t3.evidence.payloadDigest = sha256Hex(canonicalSerialize(t3.evidence.payload));
    cases.push(t3);
    const t5 = clone(a01);
    t5.evidence.payloadDigest = "zz";
    cases.push(t5);
    const t5b = clone(a01);
    t5b.evidence.payloadDigest = "sha256:" + a01.evidence.payloadDigest;
    cases.push(t5b);
    cases.push(clone(a01)); // valid baseline
    for (const c of cases) {
      const ref = verifyAssertion(clone(c), clone(receipt), NOW);
      const sec = verifyWithSecond(clone(c), clone(receipt), NOW);
      expect(sec.status).toBe(ref.status);
      if (ref.status === "INVALID") {
        expect(sec.status).toBe("INVALID");
        expect((sec as { reason: string }).reason).toBe(ref.reason);
      }
    }
  });

  // T7 — producer digest == reference recomputation == second recomputation
  it("T7: producer digest == reference recomputation == second recomputation", () => {
    const producerDigest = computePayloadDigest(a01.evidence.payload);
    const viaSharedJcs = sha256Hex(canonicalSerialize(a01.evidence.payload));
    expect(producerDigest).toBe(a01.evidence.payloadDigest);
    expect(viaSharedJcs).toBe(a01.evidence.payloadDigest);
    expect(verifyPayloadDigest(a01)).toBeNull();
    expect(secondVerifyPayloadDigest(a01)).toBeNull();
  });

  // T8 — cross-language JCS fixture verification (F8-H1 / F8-M2).
  // The PYTHON_FIXTURE_JCS and PYTHON_FIXTURE_DIGEST constants below were
  // computed OUTSIDE the repository by an independent minimal RFC 8785
  // implementation in Python 3 (probe script: %TEMP%\f9-jcs-probe.py — NOT in
  // the repo, no runtime Python dependency added to the project).
  //
  // IMPORTANT: this test does NOT use Python json.dumps (which would produce
  // 1e-07 and 1.0 instead of the ES6/JCS 1e-7 and 1). The probe implements
  // RFC 8785 canonicalization with ECMAScript Number::toString semantics.
  //
  // The test verifies that JS canonicalSerialize output matches the
  // independently computed Python JCS output byte-for-byte, AND that the
  // SHA-256 digests agree.
  //
  // SCOPE (Route B): this establishes byte-compatibility between MyShape
  // canonical JSON and RFC 8785 for I-JSON-CONFORMANT input only. It is NOT
  // an RFC 8785 conformance claim: the serialization is a serializer, not a
  // validator. The non-I-JSON boundary is pinned separately in
  // "CONFORMANCE-22: canonical JSON compatibility boundary".
  it("T8: canonical JSON bytes and digest match an independent Python RFC 8785 computation (F8-H1)", () => {
    const FIXTURE: Record<string, unknown> = {
      arr: [1, "two", null, true, -0.5],
      ctrl: "\u0001\u001f",
      emoji: "\u{1F600}",
      nbsp: "\u00a0",
      neg: -0.5,
      nested: { z: 1, a: { m: true, n: null } },
      quote: 'say "hi" and a\\b',
      ratio: 1.0,
      score: 1e-7,
      whole: 42,
    };
    const PYTHON_FIXTURE_JCS =
      '{"arr":[1,"two",null,true,-0.5],"ctrl":"\\u0001\\u001f","emoji":"\u{1F600}","nbsp":"\u00a0","neg":-0.5,"nested":{"a":{"m":true,"n":null},"z":1},"quote":"say \\"hi\\" and a\\\\b","ratio":1,"score":1e-7,"whole":42}';
    const PYTHON_FIXTURE_DIGEST =
      "5915ae680e77411541658173e014d829851e502ce3adb4086d17ba031e447d51";
    expect(canonicalSerialize(FIXTURE)).toBe(PYTHON_FIXTURE_JCS);
    expect(sha256Hex(canonicalSerialize(FIXTURE))).toBe(PYTHON_FIXTURE_DIGEST);
    // Real vector payload — Python-computed digest must equal the
    // regenerated vector's payloadDigest (T7 cross-check):
    const PYTHON_REAL_DIGEST =
      "61e3a02b6c71c1268a8fb16c9c670dea4d2640833f8e9f4f016f2ab53539c8c9";
    expect(sha256Hex(canonicalSerialize(a01.evidence.payload))).toBe(
      PYTHON_REAL_DIGEST,
    );
    // Serialization hazards pinned (language-neutral JCS contract):
    expect(canonicalSerialize({ score: 1e-7 })).toBe('{"score":1e-7}');
    expect(canonicalSerialize({ score: 1.0 })).toBe('{"score":1}');
    // JCS sorts keys — insertion order is irrelevant:
    expect(canonicalSerialize({ b: 1, a: 2 })).toBe('{"a":2,"b":1}');
  });
});

// ═══════════════════════════════════════════
// CONFORMANCE-22: Canonical JSON compatibility boundary (Route B)
//
// Pins the documented boundary as TESTED behavior. MyShape canonical JSON is
// byte-compatible with RFC 8785 (JCS) for I-JSON-conformant input, but it is
// a serializer, not a validator: it does NOT reject the inputs RFC 8785
// requires an error for.
//
// These tests exist so the boundary cannot drift silently. If the primitive
// is ever hardened to reject (Route A), these assertions must be updated
// deliberately rather than discovered by accident.
//
// Normative: CPS-0002-VERIFIER-CONTRACT.md §5.0; CPS-0002-TRUST-POLICY.md §12-D.
// No serialization behavior is changed by this suite — it only pins it.
// ═══════════════════════════════════════════

describe("CONFORMANCE-22: canonical JSON compatibility boundary (Route B)", () => {
  it("non-finite numbers serialize as null (RFC 8785 requires rejection)", () => {
    expect(canonicalSerialize({ n: NaN })).toBe('{"n":null}');
    expect(canonicalSerialize({ n: Infinity })).toBe('{"n":null}');
    expect(canonicalSerialize({ n: -Infinity })).toBe('{"n":null}');
  });

  it("non-finite numbers do not throw", () => {
    expect(() => canonicalSerialize({ n: NaN })).not.toThrow();
    expect(() => canonicalSerialize({ n: Infinity })).not.toThrow();
  });

  it("non-finite numbers are NOT reachable from JSON text", () => {
    // JSON.parse cannot produce NaN/Infinity — they arise only in-process.
    expect(() => JSON.parse("NaN")).toThrow();
    expect(() => JSON.parse("Infinity")).toThrow();
    expect(JSON.parse('{"n":null}').n).toBeNull();
  });

  it("a lone surrogate serializes as a \\uXXXX escape (RFC 8785 requires rejection)", () => {
    expect(canonicalSerialize({ s: "\ud800" })).toBe('{"s":"\\ud800"}');
    expect(() => canonicalSerialize({ s: "\ud800" })).not.toThrow();
  });

  it("a lone surrogate IS reachable from JSON text (unlike NaN / undefined)", () => {
    const parsed = JSON.parse('{"s":"\\ud800"}');
    // unpaired high surrogate — parses successfully
    expect(parsed.s.charCodeAt(0)).toBe(0xd800);
    expect(() => canonicalSerialize(parsed)).not.toThrow();
    // self-consistent: same input → same bytes
    expect(canonicalSerialize(parsed)).toBe(
      canonicalSerialize(JSON.parse('{"s":"\\ud800"}')),
    );
  });

  it("undefined members are omitted; undefined array elements become null", () => {
    expect(canonicalSerialize({ a: 1, b: undefined })).toBe('{"a":1}');
    expect(canonicalSerialize({ a: undefined })).toBe("{}");
    expect(canonicalSerialize([1, undefined, 2])).toBe("[1,null,2]");
  });

  it("conformant input matches the RFC 8785 rules (the compatible side)", () => {
    // The same rules T8 verifies against the independent Python computation.
    expect(canonicalSerialize({ n: 1.0 })).toBe('{"n":1}');
    expect(canonicalSerialize({ n: 1e-7 })).toBe('{"n":1e-7}');
    expect(canonicalSerialize({ n: 1e-6 })).toBe('{"n":0.000001}');
    expect(canonicalSerialize({ n: 1e21 })).toBe('{"n":1e+21}');
    expect(canonicalSerialize({ n: -0 })).toBe('{"n":0}');
    expect(canonicalSerialize({ b: 1, a: 2 })).toBe('{"a":2,"b":1}');
    // U+007F, U+2028, U+2029 are NOT escaped (RFC 8785 §3.2.2.2)
    expect(canonicalSerialize({ s: "\u007F" })).toBe('{"s":"\u007F"}');
    expect(canonicalSerialize({ s: "\u2028" })).toBe('{"s":"\u2028"}');
  });
});


