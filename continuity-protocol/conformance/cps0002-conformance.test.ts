    "cps-hsa-0.1-draft",
    "6fdceb85-30c0-7b90-8b2f-5594a455a369",
    "d25fc5f2bba3df7e",
    "c768f9a2ade9d12927abb1e576e0f1fffeb2eab89e6a75b5a9b357425868b215",
    "sha256:abcd1234efgh567890ijklmnopqrstuv",
